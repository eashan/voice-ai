// Usage: npx tsx scripts/gen-playground-defaults.ts [--check]
// Copies each demo agent's real greeting + prompt into apps/web/content/agentPrompts.generated.ts, the playground
// editor's defaults ("View prompt" shows exactly what runs). Agents with `sandboxPromptFile` (the concierge) expose
// that file instead: the persona part only; the locked facts are appended by the orchestrator.
// Run scripts/gen-concierge-prompt.ts first. --check exits 1 if the committed file is out of date.
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const AGENTS = new URL("../apps/orchestrator/agents/", import.meta.url);
const OUT = new URL("../apps/web/content/agentPrompts.generated.ts", import.meta.url);
/** Playground tab order. */
const FILES = ["debt-collection", "insurance-support", "roofing-support", "portfolio-concierge"];

const read = (file: string) => readFileSync(new URL(file, AGENTS), "utf8");

const entries = FILES.map((name) => {
  const cfg = JSON.parse(read(`${name}.json`)) as {
    agentId: string;
    greeting: string;
    systemPromptFile: string;
    sandboxPromptFile?: string;
  };
  const prompt = read(cfg.sandboxPromptFile ?? cfg.systemPromptFile).trimEnd();
  if (prompt.length > 4000) throw new Error(`${name}: editable prompt is ${prompt.length} chars (cap 4,000)`);
  if (cfg.greeting.length > 200) throw new Error(`${name}: greeting is over 200 chars`);
  return { agentId: cfg.agentId, slug: name, greeting: cfg.greeting, prompt };
});

const body = `// Generated by scripts/gen-playground-defaults.ts from apps/orchestrator/agents/. Do not edit.
export interface AgentPromptDefault {
  agentId: string;
  slug: string;
  greeting: string;
  prompt: string;
}

export const AGENT_PROMPTS: AgentPromptDefault[] = ${JSON.stringify(entries, null, 2)};
`;

if (process.argv.includes("--check")) {
  if ((existsSync(OUT) ? readFileSync(OUT, "utf8") : "") !== body) {
    console.error("agentPrompts.generated.ts is out of date: run npx tsx scripts/gen-playground-defaults.ts");
    process.exit(1);
  }
  console.log("playground defaults are up to date");
} else {
  writeFileSync(OUT, body);
  console.log(`wrote ${OUT.pathname} (${entries.map((e) => `${e.slug} ${e.prompt.length}`).join(", ")})`);
}
